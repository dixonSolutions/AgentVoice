#!/usr/bin/env bash
# The phone's voice cues (web/public/sounds/*.mp3 — Kenney UI Audio, CC0) as
# raw PCM for channel voice calls (docs/44). Discord plays PCM and the bridge
# does not need ffmpeg at runtime, so the clips are decoded once, here, and
# embedded in src/channels/cueAudio.generated.ts. Rerun when the MP3s change.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/src/channels/cueAudio.generated.ts"
RATE=24000
command -v ffmpeg >/dev/null || { echo "ffmpeg required" >&2; exit 1; }

{
  echo "// Generated by scripts/prepare-channel-cues.sh from web/public/sounds/*.mp3"
  echo "// (Kenney UI Audio, CC0). PCM16LE mono at CUE_RATE, base64. Do not edit."
  echo
  echo "export const CUE_RATE = $RATE;"
  echo
  echo "export const CUE_PCM_BASE64: Record<string, string> = {"
  for cue in listening sent cancel error; do
    b64="$(ffmpeg -v error -i "$ROOT/web/public/sounds/$cue.mp3" -ac 1 -ar "$RATE" -f s16le - | base64 -w0)"
    echo "  $cue: '$b64',"
  done
  echo "};"
} > "$OUT"
echo "wrote $OUT"
